test('edits a saved Pull and a saved placement from History', async () => {
  const { page } = await launch()
  const toolbar = page.getByRole('toolbar', { name: 'Modeling tools' })
  const status = page.getByTestId('engine-status')
  const steps = page.getByRole('list', { name: 'Model history' }).locator('li')
  const faces = page.getByLabel('Planar face')
  await expect(status).toHaveText(/24000 mm³/)
  await faces.selectOption({ label: 'Top · 1200 mm²' })
  await page.getByLabel('Pull distance').fill('3')
  await page.getByLabel('Pull distance').press('Enter')
  await expect(status).toHaveText(/27600 mm³/)
  await page.getByRole('button', { name: 'Edit Pull' }).click()
  const pull = page.getByRole('form', { name: 'Pull', exact: true })
  await expect(pull.getByLabel('Distance')).toHaveValue('3')
  await pull.getByLabel('Distance').fill('5')
  await pull.getByRole('button', { name: 'Apply' }).click()
  await expect(status).toHaveText(/30000 mm³/)
  await expect(steps).toHaveText(['Box', 'Pull'])

  await toolbar.getByRole('button', { name: 'Shape', exact: true }).click()
  const shape = page.getByRole('form', { name: 'Create shape' })
  await shape.getByLabel('Shape type').selectOption('cylinder')
  await shape.getByLabel('Radius').fill('5 mm')
  await shape.getByLabel('Height').fill('10 mm')
  await shape.getByRole('button', { name: 'Create', exact: true }).click()
  await faces.selectOption({ label: (await faces.locator('option', { hasText: /^Cylinder · Bottom/ }).innerText()).trim() })
  await toolbar.getByRole('button', { name: 'Stack & Place', exact: true }).click()
  await page.getByLabel('Target face').selectOption({ label: (await page.getByLabel('Target face').locator('option', { hasText: /^Box · Top/ }).innerText()).trim() })
  const place = page.getByRole('button', { name: 'Place', exact: true })
  await expect(place).toBeEnabled()
  await place.click()
  await expect(steps).toHaveText(['Box', 'Pull', 'Cylinder', 'Align'])

  await page.getByRole('button', { name: 'Edit Align' }).click()
  const align = page.getByRole('form', { name: 'Align', exact: true })
  await align.getByLabel('Offset', { exact: true }).fill('4 mm')
  await align.getByRole('button', { name: 'Apply' }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit Align' }).click()
  await expect(page.getByRole('form', { name: 'Align', exact: true }).getByLabel('Offset', { exact: true })).toHaveValue('4 mm')
})
